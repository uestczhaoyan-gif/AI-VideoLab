import Ajv from 'ajv';
import standalone from 'ajv/dist/standalone/index.js';
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';

const schema = JSON.parse(fs.readFileSync(new URL('../../shared/project.schema.json', import.meta.url), 'utf8'));
const legacy = structuredClone(schema);
legacy.$id = 'https://videolab.local/project-v1.schema.json';
const oldRoot = ['schema_version','id','created_at','title','status','execution_ready','brief','selection','template','sources','requirements','stages','cost','blockers','outputs'];
const oldBrief = ['topic','purpose','duration_seconds','aspect_ratio','resolution','fps','language','narration','subtitles','bgm','usage','notes'];
const retain = (object, keys) => { object.properties = Object.fromEntries(keys.map(k => [k, object.properties[k]])); object.required = keys; };
retain(legacy, oldRoot);
retain(legacy.properties.brief, oldBrief);
retain(legacy.properties.selection, ['template_id','template_revision','source_id','recipe_id','recipe_revision','tier']);
legacy.properties.schema_version = {const:1};
legacy.properties.selection.properties.tier = {enum:['premium','budget']};
const ajv = new Ajv({allErrors:true, strict:true, code:{source:true, esm:true}});
ajv.addSchema(schema, 'project'); ajv.addSchema(legacy, 'legacy');
let code = standalone(ajv, {validateV2:'project', validateV1:'legacy'});
// AJV's one runtime helper here counts Unicode code points. Inline its equivalent so
// the same compiled schema runs in Node and a browser with no eval or runtime bundle.
code = code.replaceAll('require("ajv/dist/runtime/ucs2length").default', '((s) => Array.from(s).length)');
if (/\brequire\(/.test(code)) throw new Error('Unexpected AJV runtime dependency; explicitly support it before changing the schema.');
code = '// Generated by tools/project/build-validator.mjs; edit project.schema.json instead.\n' + code + '\n';
const dest = new URL('../../shared/project-validator.mjs', import.meta.url);
if (process.argv.includes('--check')) {
  if (!fs.existsSync(dest) || fs.readFileSync(dest,'utf8') !== code) throw new Error('Project validator is stale; run npm run project:schema.');
  console.log('Project validator matches schema.');
} else { fs.writeFileSync(dest, code); console.log(fileURLToPath(dest)); }
